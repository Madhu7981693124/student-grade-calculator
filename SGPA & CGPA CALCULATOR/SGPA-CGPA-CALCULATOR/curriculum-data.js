export function normalizeBranchCode(branchName) {
  if (!branchName) return "CSE";
  const upper = String(branchName).trim().toUpperCase();
  // Already a valid code — return directly
  if (BRANCH_OPTIONS.some(opt => opt.code === upper)) return upper;
  // Try full-name lookup (case-insensitive)
  return _branchNameToCode[String(branchName).trim().toLowerCase()] || "CSE";
}
